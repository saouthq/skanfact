// Pont sécurisé entre le renderer et le process principal.
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('skanfact', {
  loadData: () => ipcRenderer.invoke('data:load'),
  saveData: (data, force) => ipcRenderer.invoke('data:save', { data, force: !!force }),
  listDossiers: () => ipcRenderer.invoke('dossiers:list'),
  switchDossier: (id) => ipcRenderer.invoke('dossiers:switch', id),
  addDossier: (o) => ipcRenderer.invoke('dossiers:add', o),
  shareDossier: () => ipcRenderer.invoke('dossiers:share'),
  joinDossier: (opts) => ipcRenderer.invoke('dossiers:join', opts || {}),
  renameDossier: (o) => ipcRenderer.invoke('dossiers:rename', o),
  forgetDossier: (id) => ipcRenderer.invoke('dossiers:forget', id),
  restoreDossier: (id) => ipcRenderer.invoke('dossiers:restore', id),
  renameDevice: (name) => ipcRenderer.invoke('device:rename', name),
  dataPath: () => ipcRenderer.invoke('data:path'),
  exportData: (data) => ipcRenderer.invoke('data:export', data),
  importData: (opts) => ipcRenderer.invoke('data:import', opts),
  unlock: (password) => ipcRenderer.invoke('data:unlock', password),
  lock: () => ipcRenderer.invoke('data:lock'),
  securityInfo: () => ipcRenderer.invoke('data:security'),
  setPassword: (opts) => ipcRenderer.invoke('data:setPassword', opts),
  externalBackupInfo: () => ipcRenderer.invoke('backups:externalInfo'),
  setExternalBackup: (dir) => ipcRenderer.invoke('backups:setExternal', dir),
  chooseExternalBackup: () => ipcRenderer.invoke('backups:chooseExternal'),
  openBackups: () => ipcRenderer.invoke('backups:open'),
  createBackup: (label) => ipcRenderer.invoke('backups:create', label),
  setTitle: (title) => ipcRenderer.send('window:title', title),
  setDirty: (dirty) => ipcRenderer.send('window:dirty', !!dirty),
  listBackups: () => ipcRenderer.invoke('backups:list'),
  // Regarder une sauvegarde avant de s'en servir, puis la remettre en place (7.0.0). Deux appels
  // distincts exprès : on dit ce qu'on va perdre AVANT d'écraser quoi que ce soit.
  peekBackup: (name) => ipcRenderer.invoke('backups:peek', name),
  restoreBackup: (name) => ipcRenderer.invoke('backups:restore', name),
  pickLogo: (title) => ipcRenderer.invoke('logo:pick', title),
  exportPdf: (html, suggestedName) => ipcRenderer.invoke('pdf:export', { html, suggestedName }),
  exportPdfMany: (files, folderName) => ipcRenderer.invoke('pdf:exportMany', { files, folderName }),
  saveText: (suggestedName, content) => ipcRenderer.invoke('file:saveText', { suggestedName, content }),
  openText: (opts) => ipcRenderer.invoke('file:openText', opts || {}),
  exportPdfSilent: (html, name) => ipcRenderer.invoke('pdf:exportSilent', { html, name }),
  saveTextSilent: (name, content) => ipcRenderer.invoke('file:saveSilent', { name, content }),
  composeMail: (opts) => ipcRenderer.invoke('mail:compose', opts),
  addAttachments: (docId) => ipcRenderer.invoke('attach:add', docId),
  // Lecture d'une photo de facture (4.2.0). `ocrRead` est le SEUL appel qui sort de l'ordinateur,
  // et il échoue proprement tant qu'aucune clé n'a été saisie.
  attachPath: (docId, path) => ipcRenderer.invoke('attach:addPath', { docId, path }),
  ocrStatus: () => ipcRenderer.invoke('ocr:status'),
  ocrSetKey: (key, model) => ipcRenderer.invoke('ocr:setKey', { key, model }),
  ocrPick: () => ipcRenderer.invoke('ocr:pick'),
  ocrRead: (path) => ipcRenderer.invoke('ocr:read', { path }),
  openAttachment: (docId, file) => ipcRenderer.invoke('attach:open', { docId, file }),
  revealAttachment: (docId, file) => ipcRenderer.invoke('attach:reveal', { docId, file }),
  removeAttachment: (docId, file) => ipcRenderer.invoke('attach:remove', { docId, file }),
  openPath: (p) => ipcRenderer.invoke('shell:open', p),
  showInFolder: (p) => ipcRenderer.invoke('shell:showInFolder', p),
  buildPack: (payload) => ipcRenderer.invoke('pack:build', payload),
  importCabinet: () => ipcRenderer.invoke('cabinet:import'),
  // Le dossier de clôture reçu du cabinet (9.8.0)
  lireCloture: (o) => ipcRenderer.invoke('cloture:lire', o || {}),
  ouvrirEtatsCloture: (o) => ipcRenderer.invoke('cloture:ouvrirEtats', o || {}),
  // Les questions du cabinet (9.10.0) : on LIT le fichier, le renderer décide ensuite.
  lireQuestions: (o) => ipcRenderer.invoke('questions:lire', o || {}),
  licenceStatus: (matricule) => ipcRenderer.invoke('licence:status', { matricule }),
  licenceSet: (key, matricule) => ipcRenderer.invoke('licence:set', key, { matricule }),
  licenceMail: (company, device) => ipcRenderer.invoke('licence:requestMail', { company, device }),
  // 10.14.0 — acheter depuis l'application : la commande part de la fiche société, la clé revient.
  achatTarifs: () => ipcRenderer.invoke('achat:tarifs'),
  achatCommander: (offre, company) => ipcRenderer.invoke('achat:commander', { offre, company }),
  achatVerifier: (matricule) => ipcRenderer.invoke('achat:verifier', { matricule }),
  achatOublier: (matricule) => ipcRenderer.invoke('achat:oublier', { matricule }),
  achatReprendre: () => ipcRenderer.invoke('achat:reprendre'),
  // L'éditeur (7.33.0). Ce qui repasse ce pont est un état ou une clé « SKAN1.… » signée : la clé
  // privée, elle, reste dans le processus principal.
  licenceEmettre: (payload) => ipcRenderer.invoke('licence:emettre', payload),
  editeurStatus: (depuis) => ipcRenderer.invoke('editeur:status', { depuis }),
  editeurKeygen: () => ipcRenderer.invoke('editeur:keygen'),
  editeurImporter: () => ipcRenderer.invoke('editeur:importer'),
  editeurExporter: () => ipcRenderer.invoke('editeur:exporter'),
  editeurCopierPublique: () => ipcRenderer.invoke('editeur:copierPublique'),
  cleReponseCreer: () => ipcRenderer.invoke('editeur:cleReponseCreer'),
  cleReponseCopier: (quoi) => ipcRenderer.invoke('editeur:cleReponseCopier', quoi),
  pontStatus: () => ipcRenderer.invoke('pont:status'),
  pontSetSecret: (secret) => ipcRenderer.invoke('pont:setSecret', secret),
  pontRequete: (chemin, corps) => ipcRenderer.invoke('pont:requete', chemin, corps),
  pontExporterBase: () => ipcRenderer.invoke('pont:exporterBase'),
  cleServeurCreer: () => ipcRenderer.invoke('editeur:cleServeurCreer'),
  cleServeurCopier: (quoi) => ipcRenderer.invoke('editeur:cleServeurCopier', quoi),
  onPackProgress: (cb) => { ipcRenderer.on('pack:progress', (_e, d) => cb(d)); },
  changelog: () => ipcRenderer.invoke('app:changelog'),
  // Battement de cœur du chien de garde (6.6.0) : le processus principal demande « tu es là ? »,
  // l'interface répond. Sans réponse, c'est qu'elle est bloquée — et un gel ne laisse aucune autre trace.
  onAlivePing: (cb) => { ipcRenderer.on('alive:ping', () => { ipcRenderer.send('alive:pong'); if (cb) cb(); }); },
  onFreezeNotice: (cb) => { ipcRenderer.on('freeze:notice', (_e, d) => cb(d)); },
  supportInfo: () => ipcRenderer.invoke('support:info'),
  // Une exception de l'interface part au journal (9.1.0). `send` et non `invoke` côté renderer ?
  // Non : `invoke` permet de savoir si elle a été retenue, et le garde-fou n'attend pas la réponse.
  supportErreur: (info) => ipcRenderer.invoke('support:erreur', info),
  openLog: () => ipcRenderer.invoke('support:openLog'),
  onMenuAction: (cb) => { ipcRenderer.on('menu:action', (_e, name) => cb(name)); },
  // mises à jour
  updateVersion: () => ipcRenderer.invoke('update:version'),
  updateCheck: () => ipcRenderer.invoke('update:check'),
  updateCanaux: () => ipcRenderer.invoke('update:canaux'),
  updateDownload: () => ipcRenderer.invoke('update:download'),
  updateInstall: () => ipcRenderer.invoke('update:install'),
  updateSetToken: (t) => ipcRenderer.invoke('update:setToken', t),
  updateSetBeta: (on) => ipcRenderer.invoke('update:setBeta', on),
  updateOpenReleases: () => ipcRenderer.invoke('update:openReleases'),
  onUpdateEvent: (cb) => { ipcRenderer.on('update:event', (_e, data) => cb(data)); }
});
